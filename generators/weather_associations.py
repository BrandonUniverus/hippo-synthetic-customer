"""Validate the weather association recipe and generate a read-only installed check."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

from generators.stage_check_data import UniqueLoader

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "implementation/stage-3-gateways-and-data/06-weather-associations-check.sql"
MEASUREMENT_UNITS = {
    "Temperature": {"degF", "degC"},
    "Dew Point": {"degF", "degC"},
    "Relative Humidity": {"pct"},
    "Wind Speed": {"m_per_s", "kph", "mph", "knots"},
    "Wind Direction": {"deg"},
    "Precipitation Probability": {"pct"},
}


def expected_associations(root=ROOT):
    mapping = yaml.load((root / "data/eem/northlake-eem-metaworld-stage1b-v1.yaml").read_text(encoding="utf-8"), Loader=UniqueLoader)
    points = {p["sourceChannelId"]: (meter, p) for meter in mapping["weatherIndexTargets"]["weatherMeters"] for p in meter["points"]}
    rows = []
    owners = set()
    targets = {link["relatedChannelId"] for link in mapping["weatherForecastAssociations"]}
    for link in mapping["weatherForecastAssociations"]:
        owner_meter, owner = points[link["sourceChannelId"]]
        target_meter, target = points[link["relatedChannelId"]]
        if link["sourceChannelId"] in owners or owner_meter["stationId"] != target_meter["stationId"]:
            raise ValueError("Weather associations must have unique owners and matching stations")
        if link["reasonType"] != "V" or link["relationshipKind"] != "Association" or target.get("indexType"):
            raise ValueError("Weather forecast targets must be independent Association points")
        if link["sourceChannelId"] in targets:
            raise ValueError("Weather forecast associations cannot form self-links or chains")
        measure = owner.get("measureType")
        if measure not in MEASUREMENT_UNITS or target.get("measureType") != measure:
            raise ValueError("Weather forecast endpoints must have the same supported measurement")
        if owner["unit"] not in MEASUREMENT_UNITS[measure] or target["unit"] not in MEASUREMENT_UNITS[measure]:
            raise ValueError("Weather forecast units must be compatible with the measurement")
        if owner["pointType"] != "Analog" or target["pointType"] != "Analog" or target["intervalMinutes"] != 60:
            raise ValueError("Weather forecasts require analog endpoints and an hourly target")
        owners.add(link["sourceChannelId"])
        unit_names = mapping["pointRules"]["unitListEntries"]
        rows.append({"Station": owner_meter["stationId"], "Source": owner["name"], "Target": target["name"],
                     "MeasureType": measure, "SourceUnit": unit_names[owner["unit"]].rsplit(" - (", 1)[0],
                     "TargetUnit": unit_names[target["unit"]].rsplit(" - (", 1)[0]})
    return rows


def render(root=ROOT):
    data = json.dumps(expected_associations(root), separators=(",", ":")).replace("'", "''")
    return """-- Generated by python -m generators.weather_associations. Read-only; does not create links.
IF @@SERVERNAME<>N'BVirtualPC' OR DB_NAME()<>N'EEMSuite_Northlake'
    THROW 51000, 'This check targets BVirtualPC / EEMSuite_Northlake.', 1;
DECLARE @Expected nvarchar(max)=N'""" + data + """';
SELECT e.Station,e.Source,e.Target,e.MeasureType,source.PtID AS SourcePtID,target.PtID AS ForecastPtID,
    CASE WHEN source.PtID IS NULL OR target.PtID IS NULL THEN N'Missing point'
         WHEN r.PtID IS NULL THEN N'Missing Association'
         WHEN smt.MT_MeasureName IS NULL OR tmt.MT_MeasureName IS NULL OR smt.MT_MeasureName<>e.MeasureType OR tmt.MT_MeasureName<>e.MeasureType THEN N'Incorrect measurement type'
         WHEN su.UN_Name IS NULL OR tu.UN_Name IS NULL OR su.UN_Name<>e.SourceUnit OR tu.UN_Name<>e.TargetUnit OR target.Interval<>60 THEN N'Incorrect unit or forecast interval'
         WHEN target.PtGatewayID IS NULL OR source.PtGatewayID IS NULL THEN N'Missing gateway'
         WHEN EXISTS(SELECT 1 FROM dbo.PointBaseline b WHERE b.PtID=target.PtID) THEN N'Forecast incorrectly configured as baseline'
         ELSE N'Configured' END AS Result
FROM OPENJSON(@Expected) WITH(Station nvarchar(32),Source nvarchar(64),Target nvarchar(64),MeasureType nvarchar(64),SourceUnit nvarchar(64),TargetUnit nvarchar(64)) e
LEFT JOIN dbo.Meter m ON m.SM_Code=e.Station
LEFT JOIN dbo.MetaWorld_TBL sw ON sw.ParentID=m.MetaWorldID AND sw.Description=e.Source
LEFT JOIN dbo.PointDef_TBL source ON source.MetaWorldID=sw.MetaWorldID
LEFT JOIN dbo.MetaWorld_TBL tw ON tw.ParentID=m.MetaWorldID AND tw.Description=e.Target
LEFT JOIN dbo.PointDef_TBL target ON target.MetaWorldID=tw.MetaWorldID
LEFT JOIN dbo.MeasureType smt ON smt.MT_MeasureTypeID=source.MT_MeasureTypeID
LEFT JOIN dbo.MeasureType tmt ON tmt.MT_MeasureTypeID=target.MT_MeasureTypeID
LEFT JOIN dbo.Unit su ON su.UN_UnitID=source.UN_UnitID
LEFT JOIN dbo.Unit tu ON tu.UN_UnitID=target.UN_UnitID
LEFT JOIN dbo.PtRelatedData_TBL r ON r.PtID=source.PtID AND r.RelatedPtID=target.PtID
    AND r.ReasonType=N'V' AND r.RelationshipKind=N'Association'
ORDER BY e.Station,e.Source;
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            parser.exit(1, "Weather association check is stale; run python -m generators.weather_associations\n")
        print("Weather association check matches the YAML.")
    else:
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
