/* Northlake Stage 3, Step 2: direct gateway point assignments.
   Generated by python -m generators.gateway_assignments. Do not edit the data block.
   Run this whole file in SSMS against BVirtualPC / EEMSuite_Northlake.
   @Apply = 0 is READ-ONLY PREVIEW. Review all result sets before changing it to 1.
   Optional @ProfileKey limits both preview and apply to one gateway recipe key.
   @AllowLegacyWeatherMigration = 1 permits only the exact nine old weather
   bindings recorded in the recipe. It never permits arbitrary overwrites.
   Apply uses the application's dbo.GwPtParam_Save, in one checked transaction.
   No points, aggregates, gateways, nodes, tasks, readings, or HMR rows are created.
   The 204 handheld registers (192 meters) belong to 05-handheld-routes.yaml and are
   excluded: HMR_PointNode_Get reads HMR_Reading, not GwPtParam/GwNodeID bindings.
   This manual SQL path records LastChangedBy but does not emit application audit events.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
DECLARE @Apply bit = 0;
DECLARE @ProfileKey nvarchar(128) = NULL;
DECLARE @AllowLegacyWeatherMigration bit = 0;

IF CONVERT(nvarchar(128), SERVERPROPERTY('ServerName')) <> N'BVirtualPC'
   OR DB_NAME() <> N'EEMSuite_Northlake'
    THROW 51000, 'Wrong target. Use BVirtualPC / EEMSuite_Northlake.', 1;
IF @@TRANCOUNT <> 0
    THROW 51000, 'Run outside an existing transaction.', 1;

-- SOURCE HASHES
DECLARE @Expected nvarchar(max) = N'__EXPECTED_JSON__';

DROP TABLE IF EXISTS #Profiles, #Nodes, #Bindings, #Resolved, #PreviewPoints, #Parameters, #LegacyWeather, #Issues, #Before, #BeforeAggregates;
CREATE TABLE #Issues (Item nvarchar(512), Problem nvarchar(512));
SELECT j.[Key], j.Name, j.Vendor, ids.Matches, ids.GatewayID
INTO #Profiles
FROM OPENJSON(@Expected, '$.Profiles') WITH ([Key] nvarchar(128), Name nvarchar(255), Vendor nvarchar(128)) j
OUTER APPLY (SELECT COUNT(*) Matches, MIN(o.hSiERtdb) GatewayID FROM dbo.ObjectRegistry o
             JOIN dbo.GWVendor v ON v.GwVendorID=o.GwVendorID
             WHERE o.Descriptor=j.Name AND v.Description=j.Vendor) ids
WHERE j.Vendor IS NOT NULL AND (@ProfileKey IS NULL OR j.[Key]=@ProfileKey);

IF NOT EXISTS(SELECT 1 FROM #Profiles)
    THROW 51000, 'No direct-binding profile matches @ProfileKey. Handheld routes use Step 5.', 1;
INSERT #Issues SELECT Name, N'Gateway name/type must resolve exactly once.' FROM #Profiles WHERE Matches<>1;

SELECT j.Profile, j.[Key], j.Name, j.Params, p.GatewayID, ids.Matches, ids.GwNodeID
INTO #Nodes
FROM OPENJSON(@Expected, '$.Nodes') WITH (Profile nvarchar(128), [Key] nvarchar(128), Name nvarchar(255), Params nvarchar(max) AS JSON) j
JOIN #Profiles p ON p.[Key]=j.Profile
OUTER APPLY (SELECT COUNT(*) Matches, MIN(n.GwNodeID) GwNodeID FROM dbo.GwNodes n
             WHERE n.PtGatewayID=p.GatewayID AND n.Description=j.Name) ids;
INSERT #Issues SELECT Name, N'Node must resolve exactly once under its expected gateway.' FROM #Nodes WHERE Matches<>1;

-- Verify label-to-column metadata before any values could be written.
INSERT #Issues
SELECT CONCAT(j.Vendor,N' / ',j.Label), N'Gateway parameter column, label, or type differs from the recipe.'
FROM OPENJSON(@Expected, '$.Metadata') WITH (Vendor nvarchar(128), [Column] int, Label nvarchar(128), [Type] nvarchar(32)) j
WHERE EXISTS(SELECT 1 FROM #Profiles p WHERE p.Vendor=j.Vendor)
AND (SELECT COUNT(*) FROM dbo.GWVendor v JOIN dbo.GWVendorParam p ON p.GwVendorID=v.GwVendorID
     WHERE v.Description=j.Vendor AND p.GWParamID=j.[Column] AND p.GWParamLabel=j.Label
       AND p.GWParamType=CASE j.[Type] WHEN N'Integer' THEN 3 WHEN N'Decimal' THEN 5 WHEN N'Boolean' THEN 11 WHEN N'String' THEN 30 END)<>1;

-- Only explicitly required node values are checked. FIG's unread editor defaults
-- are immaterial; scheduling flags must still remain disabled for every node.
INSERT #Issues
SELECT CONCAT(n.Name,N' / Node Parameter ',CONVERT(int,e.[key])+1), N'Required node value differs from the recipe.'
FROM #Nodes n JOIN dbo.GwNodes live ON live.GwNodeID=n.GwNodeID
CROSS APPLY OPENJSON(n.Params) e
CROSS APPLY (VALUES (0,live.GwNodeParam1),(1,live.GwNodeParam2),(2,live.GwNodeParam3),(3,live.GwNodeParam4),(4,live.GwNodeParam5),
    (5,live.GwNodeParam6),(6,live.GwNodeParam7),(7,live.GwNodeParam8),(8,live.GwNodeParam9),(9,live.GwNodeParam10),
    (10,live.GwNodeParam11),(11,live.GwNodeParam12),(12,live.GwNodeParam13),(13,live.GwNodeParam14),(14,live.GwNodeParam15)) a(Pos,Value)
WHERE a.Pos=CONVERT(int,e.[key]) AND e.[type]<>0
  AND (ISNULL(a.Value,N'') COLLATE Latin1_General_100_BIN2<>e.Value COLLATE Latin1_General_100_BIN2 OR DATALENGTH(ISNULL(a.Value,N''))<>DATALENGTH(e.Value));
INSERT #Issues
SELECT n.Name,N'Node scheduling must remain Disabled, with late intervals and data gaps off.'
FROM #Nodes n JOIN dbo.GwNodes live ON live.GwNodeID=n.GwNodeID
WHERE ISNULL(live.NextBatchMethodID,0)<>0 OR ISNULL(live.EnableLateIntervals,0)<>0 OR ISNULL(live.EnableDataGaps,0)<>0;

SELECT j.* INTO #Bindings
FROM OPENJSON(@Expected, '$.Points') WITH (
    Channel nvarchar(128), Profile nvarchar(128), Node nvarchar(128), Company nvarchar(128), Meter nvarchar(128),
    Parent nvarchar(255), Point nvarchar(255), ReadingType nvarchar(32), Interval int, Params nvarchar(max) AS JSON,
    Legacy nvarchar(max) AS JSON) j
JOIN #Profiles pr ON pr.[Key]=j.Profile;

-- No illustrative model IDs, fuzzy matching, or point creation. Both the point
-- definition and its active hierarchy node must agree on the owning company.
SELECT b.*, n.GatewayID, n.GwNodeID, ids.Matches, ids.PtID,
       CONVERT(nvarchar(32),N'') AS AssignmentStatus
INTO #Resolved FROM #Bindings b JOIN #Nodes n ON n.[Key]=b.Node AND n.Profile=b.Profile
OUTER APPLY (
    SELECT COUNT(*) Matches, MIN(p.PtID) PtID
    FROM dbo.PointDef_TBL p
    JOIN dbo.MetaWorld_TBL mw ON mw.MetaWorldID=p.MetaWorldID AND mw.PtID=p.PtID AND mw.CompanyID=p.CompanyID
    JOIN dbo.Company_TBL c ON c.CompanyID=mw.CompanyID
    JOIN dbo.MetaWorld_TBL parent ON parent.MetaWorldID=mw.ParentID AND parent.CompanyID=mw.CompanyID AND ISNULL(parent.DeleteInd,0)=0
    LEFT JOIN dbo.Meter m ON m.MetaWorldID=parent.MetaWorldID
    WHERE c.CompanyName=b.Company AND p.Description=b.Point AND parent.Description=b.Parent
      AND ISNULL(m.SM_Code,N'')=b.Meter AND ISNULL(mw.DeleteInd,0)=0 AND mw.InternalLevelNbr=5
) ids;
INSERT #Issues SELECT Channel, N'Active Stage 2 point identity must resolve exactly once.' FROM #Resolved WHERE Matches<>1;
INSERT #Issues SELECT Channel,N'The same point resolved for more than one assignment.' FROM #Resolved
WHERE PtID IN(SELECT PtID FROM #Resolved WHERE PtID IS NOT NULL GROUP BY PtID HAVING COUNT(*)>1);
SELECT p.* INTO #PreviewPoints FROM dbo.PointDef_TBL p JOIN #Resolved r ON r.PtID=p.PtID;
INSERT #Issues
SELECT r.Channel,N'Point is a derived/aggregate output or its reading type/interval differs from Stage 2.'
FROM #Resolved r JOIN #PreviewPoints p ON p.PtID=r.PtID
WHERE p.PtType<>CASE r.ReadingType WHEN N'Analog' THEN 1 WHEN N'Digital' THEN 2 WHEN N'Accumulator' THEN 3 ELSE -1 END
   OR p.Interval<>r.Interval OR p.PtType>=4
   OR EXISTS(SELECT 1 FROM dbo.PtRelatedData_TBL rel WHERE rel.RelatedPtID=p.PtID AND rel.RelationshipKind=N'Derived')
   OR EXISTS(SELECT 1 FROM dbo.PointAggregatePoints agg WHERE agg.AggregatePtID=p.PtID);

SELECT r.Channel, CONVERT(int,e.[key])+1 AS ParameterNumber, CONVERT(nvarchar(255),e.Value) AS ExpectedValue,
       CONVERT(nvarchar(255),a.Value) AS CurrentValue
INTO #Parameters FROM #Resolved r JOIN #PreviewPoints p ON p.PtID=r.PtID
CROSS APPLY OPENJSON(r.Params) e
CROSS APPLY (VALUES (0,p.GwPtParam1),(1,p.GwPtParam2),(2,p.GwPtParam3),(3,p.GwPtParam4),(4,p.GwPtParam5),
    (5,p.GwPtParam6),(6,p.GwPtParam7),(7,p.GwPtParam8),(8,p.GwPtParam9),(9,p.GwPtParam10),
    (10,p.GwPtParam11),(11,p.GwPtParam12),(12,p.GwPtParam13),(13,p.GwPtParam14),(14,p.GwPtParam15)) a(Pos,Value)
WHERE a.Pos=CONVERT(int,e.[key]);

-- An explicit opt-in recognizes only a complete historical weather snapshot:
-- owning gateway name, node name and all fifteen point parameter values.
-- Anything else still fails the ordinary conflict checks below.
SELECT r.Channel, p.PtGatewayID AS PreviousGatewayID, p.GwNodeID AS PreviousNodeID,
       oldg.Descriptor AS PreviousGateway, oldn.Description AS PreviousNode
INTO #LegacyWeather
FROM #Resolved r JOIN #PreviewPoints p ON p.PtID=r.PtID
JOIN dbo.ObjectRegistry oldg ON oldg.hSiERtdb=p.PtGatewayID
JOIN dbo.GwNodes oldn ON oldn.GwNodeID=p.GwNodeID AND oldn.PtGatewayID=p.PtGatewayID
WHERE @AllowLegacyWeatherMigration=1 AND r.Profile=N'gw_noaa_ksac_observations'
  AND oldn.Description=JSON_VALUE(r.Legacy,'$.Node')
  AND EXISTS(SELECT 1 FROM OPENJSON(r.Legacy,'$.GatewayNames') names WHERE names.Value=oldg.Descriptor)
  AND (SELECT COUNT(*) FROM OPENJSON(r.Legacy,'$.Params'))=15
  AND NOT EXISTS(
      SELECT 1 FROM OPENJSON(r.Legacy,'$.Params') expected
      JOIN #Parameters actual ON actual.Channel=r.Channel AND actual.ParameterNumber=CONVERT(int,expected.[key])+1
      WHERE ISNULL(actual.CurrentValue,N'') COLLATE Latin1_General_100_BIN2<>ISNULL(expected.Value,N'') COLLATE Latin1_General_100_BIN2
         OR DATALENGTH(ISNULL(actual.CurrentValue,N''))<>DATALENGTH(ISNULL(expected.Value,N'')));
INSERT #Issues
SELECT r.Channel,N'Point already has a different gateway or node; no overwrite is allowed.'
FROM #Resolved r JOIN #PreviewPoints p ON p.PtID=r.PtID
WHERE ((ISNULL(p.PtGatewayID,0)<>0 AND p.PtGatewayID<>r.GatewayID)
   OR (ISNULL(p.GwNodeID,0)<>0 AND p.GwNodeID<>r.GwNodeID))
  AND NOT EXISTS(SELECT 1 FROM #LegacyWeather legacy WHERE legacy.Channel=r.Channel);
INSERT #Issues
SELECT CONCAT(Channel,N' / Point Parameter ',ParameterNumber),N'Existing nonblank parameter conflicts with the recipe.'
FROM #Parameters WHERE ISNULL(CurrentValue,N'')<>N''
AND (CurrentValue COLLATE Latin1_General_100_BIN2<>ISNULL(ExpectedValue,N'') COLLATE Latin1_General_100_BIN2
     OR DATALENGTH(CurrentValue)<>DATALENGTH(ISNULL(ExpectedValue,N'')))
AND NOT EXISTS(SELECT 1 FROM #LegacyWeather legacy WHERE legacy.Channel=#Parameters.Channel);

UPDATE r SET AssignmentStatus=CASE WHEN p.PtGatewayID=r.GatewayID AND p.GwNodeID=r.GwNodeID
    AND NOT EXISTS(SELECT 1 FROM #Parameters v WHERE v.Channel=r.Channel
        AND (ISNULL(v.CurrentValue,N'') COLLATE Latin1_General_100_BIN2<>ISNULL(v.ExpectedValue,N'') COLLATE Latin1_General_100_BIN2
             OR DATALENGTH(ISNULL(v.CurrentValue,N''))<>DATALENGTH(ISNULL(v.ExpectedValue,N''))))
    THEN N'ALREADY CORRECT'
    WHEN EXISTS(SELECT 1 FROM #LegacyWeather legacy WHERE legacy.Channel=r.Channel) THEN N'READY TO MIGRATE'
    ELSE N'READY TO ASSIGN' END
FROM #Resolved r JOIN #PreviewPoints p ON p.PtID=r.PtID;

SELECT @@SERVERNAME AS ServerName, DB_NAME() AS DatabaseName, @Apply AS ApplyChanges,
       @AllowLegacyWeatherMigration AS AllowLegacyWeatherMigration,
       (SELECT COUNT(*) FROM #Resolved) AS DirectBindings, (SELECT COUNT(*) FROM #Issues) AS BlockingIssues;
SELECT p.[Key] AS ProfileKey,p.Name, r.AssignmentStatus,COUNT(r.Channel) AS Points
FROM #Profiles p LEFT JOIN #Resolved r ON r.Profile=p.[Key]
GROUP BY p.[Key],p.Name,r.AssignmentStatus ORDER BY p.Name,r.AssignmentStatus;
SELECT Item,Problem FROM #Issues ORDER BY Item;
SELECT Channel,Company,Meter,Point,PtID,GatewayID,GwNodeID,AssignmentStatus
FROM #Resolved ORDER BY Profile,Node,Channel;
SELECT * FROM #LegacyWeather ORDER BY Channel;
SELECT Channel,ParameterNumber,CurrentValue,ExpectedValue FROM #Parameters
WHERE CurrentValue IS NOT NULL OR ExpectedValue IS NOT NULL ORDER BY Channel,ParameterNumber;

IF EXISTS(SELECT 1 FROM #Issues)
    THROW 51000, 'Preflight failed. Nothing was changed; resolve the reported issues and run again.', 1;
IF @Apply=0
BEGIN
    PRINT 'PREVIEW ONLY: no persistent changes. Set @Apply=1 only after reviewing this preview.';
    RETURN;
END;
IF NOT EXISTS(SELECT 1 FROM dbo.ValidUser WHERE UserID IS NOT NULL)
   OR NOT EXISTS(SELECT 1 FROM dbo.Permissions WHERE PermissionType=N'AR' AND MetaKey=N'system_administrator' AND AuthLevel=3)
    THROW 51000, 'Apply requires an EEM system administrator recognized by ValidUser/Permissions.', 1;

BEGIN TRY
    BEGIN TRANSACTION;
    -- Lock the target definitions before applying. Detect a change since preview
    -- rather than overwriting it. The complete row snapshot is compared below.
    SELECT p.* INTO #Before FROM dbo.PointDef_TBL p WITH(UPDLOCK,HOLDLOCK)
    JOIN #Resolved r ON r.PtID=p.PtID;
    IF EXISTS(SELECT * FROM #PreviewPoints EXCEPT SELECT * FROM #Before)
       OR EXISTS(SELECT * FROM #Before EXCEPT SELECT * FROM #PreviewPoints)
        THROW 51000, 'A point definition changed during preflight. Run preview again.', 1;
    -- EXCEPT uses each column's collation. Parameter tokens may be case-sensitive
    -- to the gateway even when the database collation is not.
    IF EXISTS(SELECT 1 FROM #Before p JOIN #Resolved r ON r.PtID=p.PtID
        CROSS APPLY (VALUES (1,p.GwPtParam1),(2,p.GwPtParam2),(3,p.GwPtParam3),(4,p.GwPtParam4),(5,p.GwPtParam5),
           (6,p.GwPtParam6),(7,p.GwPtParam7),(8,p.GwPtParam8),(9,p.GwPtParam9),(10,p.GwPtParam10),
           (11,p.GwPtParam11),(12,p.GwPtParam12),(13,p.GwPtParam13),(14,p.GwPtParam14),(15,p.GwPtParam15)) a(Pos,Value)
        JOIN #Parameters v ON v.Channel=r.Channel AND v.ParameterNumber=a.Pos
        WHERE ISNULL(a.Value,N'') COLLATE Latin1_General_100_BIN2<>ISNULL(v.CurrentValue,N'') COLLATE Latin1_General_100_BIN2
           OR DATALENGTH(ISNULL(a.Value,N''))<>DATALENGTH(ISNULL(v.CurrentValue,N'')))
        THROW 51000, 'A point parameter changed during preflight. Run preview again.', 1;
    SELECT agg.* INTO #BeforeAggregates FROM dbo.PointAggregatePoints agg WITH(HOLDLOCK)
    WHERE EXISTS(SELECT 1 FROM #Resolved r WHERE r.PtID=agg.PtID OR r.PtID=agg.AggregatePtID);
    IF EXISTS(SELECT 1 FROM #BeforeAggregates a JOIN #Resolved r ON r.PtID=a.AggregatePtID)
       OR EXISTS(SELECT 1 FROM dbo.PtRelatedData_TBL rel WITH(HOLDLOCK) JOIN #Resolved r ON r.PtID=rel.RelatedPtID WHERE rel.RelationshipKind=N'Derived')
        THROW 51000, 'A target became a derived or aggregate output during preflight.', 1;

    DECLARE @PtID int,@GatewayID int,@NodeID int,@Params nvarchar(max),@Changed int=0;
    DECLARE assignments CURSOR LOCAL FAST_FORWARD FOR
        SELECT PtID,GatewayID,GwNodeID,Params FROM #Resolved
        WHERE AssignmentStatus IN(N'READY TO ASSIGN',N'READY TO MIGRATE') ORDER BY PtID;
    OPEN assignments;
    FETCH NEXT FROM assignments INTO @PtID,@GatewayID,@NodeID,@Params;
    WHILE @@FETCH_STATUS=0
    BEGIN
        DECLARE @p1 nvarchar(255)=JSON_VALUE(@Params,'$[0]'),@p2 nvarchar(255)=JSON_VALUE(@Params,'$[1]'),
            @p3 nvarchar(255)=JSON_VALUE(@Params,'$[2]'),@p4 nvarchar(255)=JSON_VALUE(@Params,'$[3]'),
            @p5 nvarchar(255)=JSON_VALUE(@Params,'$[4]'),@p6 nvarchar(255)=JSON_VALUE(@Params,'$[5]'),
            @p7 nvarchar(255)=JSON_VALUE(@Params,'$[6]'),@p8 nvarchar(255)=JSON_VALUE(@Params,'$[7]'),
            @p9 nvarchar(255)=JSON_VALUE(@Params,'$[8]'),@p10 nvarchar(255)=JSON_VALUE(@Params,'$[9]'),
            @p11 nvarchar(255)=JSON_VALUE(@Params,'$[10]'),@p12 nvarchar(255)=JSON_VALUE(@Params,'$[11]'),
            @p13 nvarchar(255)=JSON_VALUE(@Params,'$[12]'),@p14 nvarchar(255)=JSON_VALUE(@Params,'$[13]'),
            @p15 nvarchar(255)=JSON_VALUE(@Params,'$[14]');
        EXEC dbo.GwPtParam_Save @PtID=@PtID,@PtGatewayID=@GatewayID,@GwNodeID=@NodeID,
            @GwPtParam1=@p1,@GwPtParam2=@p2,@GwPtParam3=@p3,@GwPtParam4=@p4,@GwPtParam5=@p5,
            @GwPtParam6=@p6,@GwPtParam7=@p7,@GwPtParam8=@p8,@GwPtParam9=@p9,@GwPtParam10=@p10,
            @GwPtParam11=@p11,@GwPtParam12=@p12,@GwPtParam13=@p13,@GwPtParam14=@p14,@GwPtParam15=@p15;
        SET @Changed+=1;
        FETCH NEXT FROM assignments INTO @PtID,@GatewayID,@NodeID,@Params;
    END;
    CLOSE assignments;
    DEALLOCATE assignments;

    IF EXISTS(SELECT 1 FROM #Resolved r LEFT JOIN dbo.PointDef_TBL p ON p.PtID=r.PtID
        WHERE p.PtID IS NULL OR ISNULL(p.PtGatewayID,0)<>r.GatewayID OR ISNULL(p.GwNodeID,0)<>r.GwNodeID)
        THROW 51000, 'Post-check failed: a point gateway or node did not save.', 1;
    IF EXISTS(SELECT 1 FROM #Resolved r JOIN dbo.PointDef_TBL p ON p.PtID=r.PtID
        CROSS APPLY (VALUES (1,p.GwPtParam1),(2,p.GwPtParam2),(3,p.GwPtParam3),(4,p.GwPtParam4),(5,p.GwPtParam5),
           (6,p.GwPtParam6),(7,p.GwPtParam7),(8,p.GwPtParam8),(9,p.GwPtParam9),(10,p.GwPtParam10),
           (11,p.GwPtParam11),(12,p.GwPtParam12),(13,p.GwPtParam13),(14,p.GwPtParam14),(15,p.GwPtParam15)) a(Pos,Value)
        JOIN #Parameters v ON v.Channel=r.Channel AND v.ParameterNumber=a.Pos
        WHERE ISNULL(a.Value,N'') COLLATE Latin1_General_100_BIN2<>ISNULL(v.ExpectedValue,N'') COLLATE Latin1_General_100_BIN2
           OR DATALENGTH(ISNULL(a.Value,N''))<>DATALENGTH(ISNULL(v.ExpectedValue,N'')))
        THROW 51000, 'Post-check failed: a point parameter did not save.', 1;

    -- Bring only the permitted fields in the comparison copy up to the saved
    -- values, then compare every point-definition column with the live row.
    UPDATE b SET PtGatewayID=p.PtGatewayID,GwNodeID=p.GwNodeID,
        GwPtParam1=p.GwPtParam1,GwPtParam2=p.GwPtParam2,GwPtParam3=p.GwPtParam3,GwPtParam4=p.GwPtParam4,GwPtParam5=p.GwPtParam5,
        GwPtParam6=p.GwPtParam6,GwPtParam7=p.GwPtParam7,GwPtParam8=p.GwPtParam8,GwPtParam9=p.GwPtParam9,GwPtParam10=p.GwPtParam10,
        GwPtParam11=p.GwPtParam11,GwPtParam12=p.GwPtParam12,GwPtParam13=p.GwPtParam13,GwPtParam14=p.GwPtParam14,GwPtParam15=p.GwPtParam15,
        AsOfDate=p.AsOfDate,LastChangedBy=p.LastChangedBy
    FROM #Before b JOIN dbo.PointDef_TBL p ON p.PtID=b.PtID;
    IF EXISTS(SELECT * FROM #Before EXCEPT SELECT p.* FROM dbo.PointDef_TBL p JOIN #Resolved r ON r.PtID=p.PtID)
        THROW 51000, 'Post-check failed: a point definition changed outside its binding fields.', 1;
    IF EXISTS(SELECT * FROM #BeforeAggregates EXCEPT SELECT a.* FROM dbo.PointAggregatePoints a
              WHERE EXISTS(SELECT 1 FROM #Resolved r WHERE r.PtID=a.PtID OR r.PtID=a.AggregatePtID))
       OR EXISTS(SELECT a.* FROM dbo.PointAggregatePoints a
              WHERE EXISTS(SELECT 1 FROM #Resolved r WHERE r.PtID=a.PtID OR r.PtID=a.AggregatePtID)
              EXCEPT SELECT * FROM #BeforeAggregates)
        THROW 51000, 'Post-check failed: an aggregate membership changed.', 1;
    COMMIT;
    SELECT N'APPLIED AND VERIFIED' AS Result,@Changed AS ChangedPoints,
        (SELECT COUNT(*) FROM #Resolved)-@Changed AS AlreadyCorrectPoints;
END TRY
BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK;
    THROW;
END CATCH;
